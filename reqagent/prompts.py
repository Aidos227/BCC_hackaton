def verify_prompt(doc_text: str, findings_json: str) -> str:
    return f"""Ты — независимый скептический рецензент. Тебе дан документ и черновые замечания,
собранные несколькими проверками (review — проверка требования, set — проверка набора,
oracle — трассировка сценария по правилам, model — исполняемая модель с результатами прогона,
rule — детерминированное правило).
Проверь КАЖДОЕ замечание по тексту документа.

Для каждого замечания реши:
- "confirm" — дефект реально следует из процитированного текста;
- "reject" — замечание не подтверждается текстом: вопрос уже решён в другом месте документа
  (обязательно поищи ответ во всех частях, включая API, статусы и особые правила),
  неверно прочитано, или это общее рассуждение без опоры на текст. Для model-замечаний отклоняй,
  если модель реализовала правило не так, как оно написано;
- "question" — это не дефект текста, а продуктовое решение, которое должен принять владелец;
- "duplicate" — то же самое, что другое замечание (укажи "duplicate_of"). Из группы дублей оставляй
  как основное то, у которого сильнее доказательство: oracle/model > set > review > rule.
  Дубли ищи по сути (одна и та же причина в одном и том же месте), а не по словам.

Уточни критичность по правилам:
- critical — только если можно назвать конкретное решение разработки/тестирования, которое невозможно
  принять по тексту (и это решение назови в "blocked_decision"). Противоречие critical — только если две
  процитированные места документа предписывают НЕСОВМЕСТИМЫЕ результаты для одной ситуации. Нарушение общей
  практики или стандарта (например, семантики HTTP-методов), которое документ сам себе не противоречит, —
  не противоречие документа: это major.
- иначе major или minor.

Верни JSON: {{"verdicts": [{{"id": "C-..", "verdict": "confirm|reject|question|duplicate",
"duplicate_of": "C-..|null", "severity": "critical|major|minor", "reason": "<1 предложение>",
"blocked_decision": "<для critical>", "owner_question": "<для question или если нужен выбор владельца>"}}]}}
В списке должны быть все id.

Черновые замечания:
{findings_json}

Документ:
<<<
{doc_text}
>>>"""


